def test_zip_excludes_local_state(tmp_path, fake_cli):
    result = build_project(parse_blueprint(MINIMAL_BLUEPRINT), tmp_path, runner=fake_cli)
    (result.project_dir / "app/__pycache__").mkdir()
    (result.project_dir / "app/__pycache__/agent.cpython-311.pyc").write_bytes(b"")

    files = project_files(result.project_dir)
    assert ".env.example" in files and "app/agent.py" in files
    assert not [f for f in files if f == ".env" or ".venv" in f or "__pycache__" in f]

    with zipfile.ZipFile(io.BytesIO(zip_project(result.project_dir))) as archive:
        assert sorted(archive.namelist()) == [f"tiny-agent/{f}" for f in files]



def test_scaffold_command():
    bp = load_blueprint("blueprints/support_team.yml")
    cmd = scaffold_command(bp, generator.Path("/out"))
    assert cmd[:3] == ["agents-cli", "create", "support-team"]
    flags = dict(zip(cmd[3::2], cmd[4::2], strict=False))
    assert flags["--deployment-target"] == "cloud_run"
    assert flags["--root-agent-name"] == "triage"
    assert flags["--region"] == "us-central1"
    assert flags["--output-dir"] == "/out"
    for flag in ("--prototype", "--yes", "--skip-checks"):
        assert flag in cmd
    assert "--agent-gateway" not in cmd


def test_agent_gateway_flag():
    data = yaml.safe_load(MINIMAL_BLUEPRINT)
    data["deployment"] = {"agent_gateway": True}
    assert "--agent-gateway" in scaffold_command(parse_blueprint(yaml.safe_dump(data)), generator.Path("/o"))


def test_agents_cli_command_resolution(monkeypatch):
    monkeypatch.setenv("AGENTS_CLI", "uvx google-agents-cli")
    assert generator.agents_cli_command() == ["uvx", "google-agents-cli"]
    monkeypatch.delenv("AGENTS_CLI")
    monkeypatch.setattr(generator.shutil, "which", lambda name: None)
    assert generator.agents_cli_command()[1:] == ["-m", "google.agents.cli.main"]


def test_build_renders_over_scaffold(tmp_path, fake_cli):
    bp = load_blueprint("blueprints/dice_mcp_agent.yml")
    result = build_project(bp, tmp_path, runner=fake_cli)
    project = tmp_path / "dice-mcp-agent"

    assert result.project_dir == project
    assert "tests/eval/tool_calls.py" in result.files_written
    assert "scaffold placeholder" not in (project / "app/agent.py").read_text()
    assert load_blueprint(project / "blueprint.yml") == bp

    for env_file in (".env", ".env.example"):
        text = (project / env_file).read_text()
        assert "GOOGLE_CLOUD_PROJECT=your-gcp-project-id" in text
        assert text.count("MCP_SERVER_URL=http://127.0.0.1:8080/mcp") == 1

    pyproject = tomlkit.parse((project / "pyproject.toml").read_text())
    assert generator.MCP_REQUIREMENT in pyproject["project"]["dependencies"]
    assert pyproject["project"]["description"] == bp.description
    assert "Generated by agent-builder" in (project / "README.md").read_text()

    # new dependency -> re-lock so the Dockerfile's `uv sync --frozen` sees it
    assert any(c[-1] == "lock" for c in fake_cli.calls)
    assert fake_cli.commands("format"), "rendered python should be formatted"


def test_blueprint_dependencies_added_once(tmp_path, fake_cli):
    data = yaml.safe_load(MINIMAL_BLUEPRINT)
    data["dependencies"] = ["requests>=2.31", "Google-ADK[gcp]>=2.8"]  # adk already present
    build_project(parse_blueprint(yaml.safe_dump(data)), tmp_path, runner=fake_cli)
